"""Rebuild this dated review's Git inventories; no network or source changes.

Run from any directory: python3 docs/history/reproduce.py
Requires the three pinned commits in the local Git object database. Generated
files are overwritten only in docs/history/data/ and 05-master-ledger.md.
"""

import csv
import html
import io
import json
import subprocess
from collections import Counter, defaultdict
from pathlib import Path

FORK = "2f623c6607c078d1069dac23e9d8af9cb146e771"
UPSTREAM = "5c8854fd88319125125dc4b836c98b1b215b0f23"
SNAPSHOT = "7049ff0cbeb1f5ead231de4522af6b75d8d773c0"
HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
DATA = HERE / "data"


def git(*args: str) -> str:
    return subprocess.check_output(
        ["git", "--no-pager", *args], cwd=ROOT, text=True, encoding="utf-8",
        errors="backslashreplace", timeout=180,
    ).rstrip("\n")


def ascii_text(value: str) -> str:
    return value.encode("ascii", "backslashreplace").decode("ascii")


def tsv(name: str, header: list[str], rows: list[list]) -> None:
    buffer = io.StringIO()
    writer = csv.writer(buffer, delimiter="\t", lineterminator="\n")
    writer.writerow(header)
    writer.writerows(rows)
    (DATA / name).write_text(ascii_text(buffer.getvalue()), encoding="ascii")


def category(path: str) -> str:
    if path.startswith("docs/benchmarks/"):
        return "benchmark archive"
    if path.startswith("docs/research/"):
        return "research evidence"
    if path.startswith("docs/"):
        return "other docs"
    for prefix in ("ggml/src/", "ggml/include/", "tools/"):
        if path.startswith(prefix):
            return "/".join(path.split("/")[:3]) if prefix != "ggml/include/" else "ggml/include"
    return path.split("/")[0] if "/" in path else "root files"


def delta(left: str, name: str) -> list[list]:
    # No rename heuristics: path/mode/blob identity is reproducible at this scale.
    raw = git("diff", "--no-renames", "--no-ext-diff", "--no-textconv", "--raw",
              "--abbrev=40", left, FORK)
    nums = git("diff", "--no-renames", "--no-ext-diff", "--no-textconv", "--numstat", left, FORK)
    counts = {line.split("\t", 2)[2]: line.split("\t", 2)[:2]
              for line in nums.splitlines()}
    rows = []
    for line in raw.splitlines():
        meta, path = line.split("\t", 1)
        old_mode, new_mode, old_blob, new_blob, status = meta[1:].split()
        add, delete = counts[path]
        rows.append([path, status, add, delete, old_mode, new_mode, old_blob, new_blob, category(path)])
    assert len(rows) == len(counts)
    tsv(name, ["path", "status", "added_lines", "deleted_lines", "upstream_mode",
               "fork_mode", "upstream_blob", "fork_blob", "group"], rows)
    return rows


def main() -> None:
    DATA.mkdir(exist_ok=True)
    upstream_set = set(git("rev-list", UPSTREAM).splitlines())
    first_parent = git("rev-list", "--first-parent", "--reverse", FORK).splitlines()
    start = next(i for i, commit in enumerate(first_parent) if commit not in upstream_set)
    base = first_parent[start - 1]
    master = first_parent[start:]
    all_commits = git("rev-list", "--topo-order", "--reverse", FORK, "^" + base).splitlines()
    fork_only = set(git("rev-list", FORK, "^" + UPSTREAM).splitlines())
    assert set(master) <= set(all_commits)
    assert fork_only <= set(all_commits)
    assert len(master) == len(set(master))
    records = {}
    for line in git("log", "--format=%H%x09%P%x09%aI%x09%cI%x09%s", FORK, "^" + base).splitlines():
        commit, parents, authored, committed, subject = line.split("\t", 4)
        records[commit] = [commit, parents, authored, committed, subject]
    assert set(records) == set(all_commits)
    header = ["commit", "parents", "author_date", "committer_date", "subject", "first_parent", "upstream_ancestor"]
    master_set = set(master)
    tsv("all-post-divergence-commits.tsv", header,
        [records[c] + [int(c in master_set), int(c in upstream_set)] for c in all_commits])
    tsv("master-first-parent.tsv", header,
        [records[c] + [1, int(c in upstream_set)] for c in master])
    upstream_only = git("log", "--reverse", "--format=%H%x09%aI%x09%cI%x09%s", UPSTREAM, "^" + FORK)
    tsv("upstream-not-ancestors.tsv", ["commit", "author_date", "committer_date", "subject"],
        [line.split("\t", 3) for line in upstream_only.splitlines()])
    recent = git("log", "--reverse", "--format=%H%x09%cI%x09%s", UPSTREAM, "^" + SNAPSHOT)
    tsv("upstream-after-snapshot.tsv", ["commit", "committer_date", "subject"],
        [line.split("\t", 2) for line in recent.splitlines()])
    ledger = ["# Complete master first-parent ledger", "",
              "Generated by [reproduce.py](reproduce.py) from immutable commits. Read the",
              "[chronology](01-chronology.md) for interpretation. Rows are topology order;",
              "dates are committer dates, not original authorship or necessarily merge-to-master dates.",
              "Subjects are historical claims, not independently verified results. Unicode in original",
              "subjects is escaped to keep this report ASCII. Change counts are against first parent,",
              "with rename detection disabled; imported work is not all locally authored work.", "",
              "| # | Commit | Committed | Files | +lines | -lines | Subject |",
              "| ---: | --- | --- | ---: | ---: | ---: | --- |"]
    stats = {}
    with (DATA / "fork-only-commits.jsonl").open("w", encoding="ascii") as output:
        for c in all_commits:
            if c not in fork_only and c not in master_set:
                continue
            parent = records[c][1].split()[0]
            changes = git("diff", "--no-renames", "--no-ext-diff", "--no-textconv", "--numstat", parent, c)
            rows = [line.split("\t", 2) for line in changes.splitlines()]
            stats[c] = (len(rows), sum(int(r[0]) for r in rows if r[0] != "-"),
                        sum(int(r[1]) for r in rows if r[1] != "-"))
            if c in fork_only:
                output.write(json.dumps({"commit": c, "parents": records[c][1].split(),
                    "author_date": records[c][2], "committer_date": records[c][3],
                    "first_parent": c in master_set, "message": git("show", "-s", "--format=%B", c),
                    "changes_against_first_parent": rows}, ensure_ascii=True) + "\n")
    for i, c in enumerate(master, 1):
        files, add, delete = stats[c]
        subject = html.escape(ascii_text(records[c][4])).replace("|", "&#124;").replace("`", "'")
        ledger.append(f"| {i} | [{c[:9]}](https://github.com/Raudbjorn/ggml-llama.cpp/commit/{c}) | "
                      f"{records[c][3][:10]} | {files} | {add} | {delete} | {subject} |")
    (HERE / "05-master-ledger.md").write_text("\n".join(ledger) + "\n", encoding="ascii")
    current_delta = delta(UPSTREAM, "current-upstream-delta.tsv")
    snapshot_delta = delta(SNAPSHOT, "last-snapshot-delta.tsv")
    groups = defaultdict(Counter)
    for path, status, add, delete, *rest in current_delta:
        group = groups[category(path)]
        group[status] += 1
        group["files"] += 1
        group["add"] += int(add) if add != "-" else 0
        group["delete"] += int(delete) if delete != "-" else 0
    tsv("current-delta-groups.tsv", ["group", "files", "A", "M", "D", "T", "added_lines", "deleted_lines"],
        [[k, v["files"], v["A"], v["M"], v["D"], v["T"], v["add"], v["delete"]]
         for k, v in sorted(groups.items())])
    result = {"fork": FORK, "upstream": UPSTREAM, "last_snapshot_source": SNAPSHOT,
        "initial_first_parent_base": base, "first_divergent_first_parent_commit": master[0],
        "latest_merge_bases": git("merge-base", "--all", FORK, UPSTREAM).splitlines(),
        "all_post_divergence_commits": len(all_commits), "master_first_parent_commits": len(master),
        "fork_only_commits": len(fork_only), "upstream_not_ancestors": len(upstream_only.splitlines()),
        "upstream_after_snapshot": len(recent.splitlines()), "current_delta_paths": len(current_delta),
        "snapshot_delta_paths": len(snapshot_delta),
        "first_parent_committer_months": dict(sorted(Counter(records[c][3][:7] for c in master).items()))}
    (DATA / "summary.json").write_text(json.dumps(result, indent=2) + "\n", encoding="ascii")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
